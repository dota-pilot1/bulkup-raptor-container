CREATE TABLE deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    status VARCHAR(30) NOT NULL CHECK (status IN ('PREPARING', 'OUT_FOR_DELIVERY', 'DELIVERED')),
    version BIGINT NOT NULL DEFAULT 0,
    recipient_name VARCHAR(80) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    postal_code VARCHAR(10) NOT NULL,
    address VARCHAR(200) NOT NULL,
    address_detail VARCHAR(200) NOT NULL,
    center_name VARCHAR(200),
    pickup_location VARCHAR(200),
    scheduled_at TIMESTAMPTZ,
    started_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_deliveries_order UNIQUE (order_id)
);
CREATE INDEX idx_deliveries_status_created ON deliveries(status, created_at, id);
CREATE TABLE delivery_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id BIGINT NOT NULL REFERENCES deliveries(id) ON DELETE CASCADE,
    from_status VARCHAR(30) NOT NULL CHECK (from_status IN ('PREPARING', 'OUT_FOR_DELIVERY', 'DELIVERED')),
    to_status VARCHAR(30) NOT NULL CHECK (to_status IN ('PREPARING', 'OUT_FOR_DELIVERY', 'DELIVERED')),
    actor_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    reason VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_delivery_history_delivery ON delivery_status_history(delivery_id, created_at, id);
-- Existing paid orders already contain recipient snapshots. Do not invent camp or schedule data.
INSERT INTO deliveries(order_id, status, version, recipient_name, phone, postal_code, address, address_detail, created_at)
SELECT id, 'PREPARING', 0, recipient_name, phone, postal_code, address, address_detail, CURRENT_TIMESTAMP
FROM orders WHERE status = 'PAID';
