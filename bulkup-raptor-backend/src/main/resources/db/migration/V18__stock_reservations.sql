    CHECK (reserved_quantity >= 0 AND reserved_quantity <= stock_quantity);
ALTER TABLE orders DROP CONSTRAINT orders_status_check;
ALTER TABLE orders ADD CONSTRAINT orders_status_check CHECK (status IN ('CREATED', 'PAID', 'CANCELLED'));
-- Existing orders are deliberately excluded from automatic inventory settlement.
ALTER TABLE orders ADD COLUMN inventory_managed BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE stock_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN
        ('RESERVED', 'CONFIRMED', 'RELEASE_PENDING', 'RELEASED', 'REVIEW_REQUIRED')),
    expires_at TIMESTAMPTZ NOT NULL,
    next_check_at TIMESTAMPTZ NOT NULL,
    confirmed_at TIMESTAMPTZ,
    released_at TIMESTAMPTZ,
    CONSTRAINT uk_reservations_order_product UNIQUE (order_id, product_id),
    CONSTRAINT ck_reservations_timestamps CHECK (
        (status = 'CONFIRMED' AND confirmed_at IS NOT NULL AND released_at IS NULL) OR
        (status = 'RELEASED' AND released_at IS NOT NULL AND confirmed_at IS NULL) OR
        (status IN ('RESERVED', 'RELEASE_PENDING', 'REVIEW_REQUIRED')
            AND confirmed_at IS NULL AND released_at IS NULL))
);
CREATE INDEX idx_reservations_due ON stock_reservations(next_check_at, order_id)
    WHERE status IN ('RESERVED', 'RELEASE_PENDING', 'REVIEW_REQUIRED');
CREATE INDEX idx_reservations_product ON stock_reservations(product_id);

