CREATE TABLE member_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(id),
    label VARCHAR(40) NOT NULL,
    recipient_name VARCHAR(80) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    postal_code VARCHAR(5) NOT NULL,
    address VARCHAR(200) NOT NULL,
    address_detail VARCHAR(200) NOT NULL,
    default_address BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_member_addresses_member ON member_addresses(member_id);
CREATE UNIQUE INDEX uk_member_addresses_default ON member_addresses(member_id) WHERE default_address;
