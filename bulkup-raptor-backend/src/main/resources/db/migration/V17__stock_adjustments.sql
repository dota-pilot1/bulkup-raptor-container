CREATE TABLE stock_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    actor_id BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    type VARCHAR(8) NOT NULL CHECK (type IN ('INCREASE', 'DECREASE')),
    delta INTEGER NOT NULL CHECK (delta <> 0),
    before_quantity INTEGER NOT NULL CHECK (before_quantity >= 0),
    after_quantity INTEGER NOT NULL CHECK (after_quantity >= 0),
    reason VARCHAR(200) NOT NULL CHECK (CHAR_LENGTH(BTRIM(reason)) BETWEEN 1 AND 200),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_stock_adjustments_quantity
        CHECK (CAST(before_quantity AS BIGINT) + delta = CAST(after_quantity AS BIGINT)),
    CONSTRAINT ck_stock_adjustments_direction
        CHECK ((type = 'INCREASE' AND delta > 0) OR (type = 'DECREASE' AND delta < 0))
);

CREATE INDEX idx_stock_adjustments_product_created
    ON stock_adjustments(product_id, created_at DESC, id DESC);
CREATE INDEX idx_stock_adjustments_actor ON stock_adjustments(actor_id);
