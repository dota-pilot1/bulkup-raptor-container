CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(id),
    request_id UUID NOT NULL,
    request_fingerprint VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status = 'CREATED'),
    recipient_name VARCHAR(80) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    postal_code VARCHAR(10) NOT NULL,
    address VARCHAR(200) NOT NULL,
    address_detail VARCHAR(200) NOT NULL,
    items_total BIGINT NOT NULL CHECK (items_total >= 0),
    shipping_fee BIGINT NOT NULL CHECK (shipping_fee >= 0),
    total_amount BIGINT NOT NULL CHECK (total_amount = items_total + shipping_fee),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_orders_member_request UNIQUE (member_id, request_id)
);
CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
    product_name VARCHAR(80) NOT NULL,
    unit_price BIGINT NOT NULL CHECK (unit_price >= 0),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 99),
    line_total BIGINT NOT NULL CHECK (line_total = unit_price * quantity)
);
CREATE INDEX idx_order_items_order ON order_items(order_id);
CREATE INDEX idx_order_items_product ON order_items(product_id);
