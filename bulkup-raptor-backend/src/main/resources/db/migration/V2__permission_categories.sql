ALTER TABLE permissions ADD COLUMN category_id BIGINT;
UPDATE permissions p SET category_id = c.id
FROM permission_categories c
WHERE c.code = CASE
    WHEN p.code = 'PRODUCT_MANAGE' THEN 'PRODUCT'
    WHEN p.code IN ('ORDER_MANAGE', 'SHIPPING_MANAGE') THEN 'ORDER_SHIPPING'
    WHEN p.code IN ('MEMBER_MANAGE', 'MEMBER_ROLE_ASSIGN') THEN 'MEMBER'
    WHEN p.code IN ('ROLE_MANAGE', 'PERMISSION_MANAGE') THEN 'ACCESS'
    ELSE 'OTHER' END;
ALTER TABLE permissions ALTER COLUMN category_id SET NOT NULL;
ALTER TABLE permissions ADD CONSTRAINT fk_permission_category
    FOREIGN KEY (category_id) REFERENCES permission_categories(id) ON DELETE RESTRICT;
CREATE INDEX idx_permissions_category ON permissions(category_id);
