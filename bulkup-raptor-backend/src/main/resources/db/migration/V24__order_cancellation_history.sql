CREATE TABLE order_cancellation_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    event_type VARCHAR(20) NOT NULL CHECK (event_type IN ('REQUESTED','PROCESSING','FAILED','RETRIED','COMPLETED')),
    order_status VARCHAR(20) NOT NULL CHECK (order_status IN ('CREATED','PAID','CANCELLED')),
    actor_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    actor_name VARCHAR(100),
    actor_type VARCHAR(20) NOT NULL CHECK (actor_type IN ('CUSTOMER','SYSTEM')),
    reason VARCHAR(200),
    error_code VARCHAR(80),
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_order_cancellation_history_order ON order_cancellation_history(order_id, created_at, id);
CREATE UNIQUE INDEX uk_order_cancellation_requested ON order_cancellation_history(order_id) WHERE event_type='REQUESTED';
CREATE UNIQUE INDEX uk_order_cancellation_completed ON order_cancellation_history(order_id) WHERE event_type='COMPLETED';
